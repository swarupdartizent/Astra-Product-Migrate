"""Generate a SYNTHETIC Pro Suite Base baseline (astra.baseline/v1) from the synthetic golden schema.

    py -3.13 programmes/conceptone-prosuite/tools/make_baseline.py

This is not Insurity's baseline. It stands in until Insurity provides the real Pro Suite Base baseline metadata,
so baseline storage, project pinning and (in I6) the version delta engine can be exercised end to end. It applies
deliberate, documented differences to the synthetic source schema, which the delta engine must later find:
  - user-defined tables (usr_*) are customer extensions and are not in the product baseline
  - the External Programs table is removed (integrations move to REST APIs, DBQuery and webhooks)
  - WorkflowDefinition is renamed to Workflow
  - Policy gains a HomeState column
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
SCHEMA = ROOT / "packs" / "conceptone-source" / "golden" / "synthetic-v1" / "schema.sql"
OUT = ROOT / "programmes" / "conceptone-prosuite" / "baselines" / "synthetic-prosuite-base-v1.yaml"

text = SCHEMA.read_text(encoding="utf-8")
objects = []
for m in re.finditer(r"CREATE TABLE dbo\.(\w+) \((.*?)\)\s*\nGO", text, re.DOTALL):
    name, body = m.group(1), m.group(2)
    if name.startswith("usr_") or name == "ExternalProgram":
        continue
    columns = []
    for part in re.split(r",\s*(?![^()]*\))", body):
        cm = re.match(r"\s*(\w+)\s+(\w+(?:\([^)]*\))?)", part)
        if cm and cm.group(1).upper() not in ("PRIMARY", "FOREIGN", "CONSTRAINT"):
            columns.append({"name": cm.group(1), "type": cm.group(2), "nullable": "NOT NULL" not in part.upper()})
    if name == "WorkflowDefinition":
        name = "Workflow"
    if name == "Policy":
        columns.append({"name": "HomeState", "type": "char(2)", "nullable": True})
    objects.append({"type": "table", "name": name, "schema": "dbo", "columns": columns})

baseline = {
    "format": "astra.baseline/v1",
    "product": "Insurity Pro Suite Base",
    "product_version": "synthetic-1",
    "provided_by": "SYNTHETIC: generated by Artizent from the synthetic golden schema; not Insurity's baseline",
    "provided_on": "2026-11-18",
    "objects": objects,
}
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("# SYNTHETIC baseline. See make_baseline.py for what differs from the synthetic source.\n"
               + yaml.safe_dump(baseline, sort_keys=False), encoding="utf-8")
print(f"wrote {OUT} with {len(objects)} objects")
